// Builds supabase/seed.sql from src/data/referenceData.json.
// Run: node scripts/gen-seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const data = JSON.parse(readFileSync(`${root}src/data/referenceData.json`, 'utf8'));
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');
const lines = ['-- Torah lists. Generated by scripts/gen-seed-sql.mjs – run after schema.sql. Safe to re-run.', ''];

const upsert = (table, cols, rows, vals) => {
  if (!rows.length) return;
  lines.push(`insert into public.${table} (${cols.join(', ')}) values`);
  lines.push(rows.map((r) => `  (${vals(r).join(', ')})`).join(',\n'));
  const set = cols.filter((c) => c !== 'key').map((c) => `${c} = excluded.${c}`).join(', ');
  lines.push(`on conflict (key) do update set ${set};`, '');
};
upsert('categories', ['key', 'name_he', 'name_en', 'leaf_type', 'has_sections', 'sort_order'], data.categories,
  (r) => [q(r.key), q(r.name_he), q(r.name_en), q(r.leaf_type), b(r.has_sections), r.sort_order]);
upsert('sections', ['key', 'category_key', 'name_he', 'name_en', 'sort_order'], data.sections,
  (r) => [q(r.key), q(r.category_key), q(r.name_he), q(r.name_en), r.sort_order]);
upsert('books', ['key', 'category_key', 'section_key', 'name_he', 'name_en', 'item_count', 'first_item', 'track_mode', 'sort_order'], data.books,
  (r) => [q(r.key), q(r.category_key), q(r.section_key || ''), q(r.name_he), q(r.name_en), r.item_count, r.first_item, q(r.track_mode), r.sort_order]);
upsert('parshiyot', ['key', 'book_key', 'name_he', 'name_en', 'sort_order', 'aliyah_ranges'], data.parshiyot,
  (r) => [q(r.key), q(r.book_key), q(r.name_he), q(r.name_en), r.sort_order, `'${JSON.stringify(r.aliyah_ranges)}'::jsonb`]);
upsert('aliyot', ['key', 'name_he', 'name_en', 'sort_order', 'in_study'], data.aliyot,
  (r) => [q(r.key), q(r.name_he), q(r.name_en), r.sort_order, b(r.in_study)]);

writeFileSync(`${root}supabase/seed.sql`, lines.join('\n'));
console.log('wrote supabase/seed.sql', lines.length, 'lines');
